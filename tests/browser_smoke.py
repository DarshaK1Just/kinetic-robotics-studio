from pathlib import Path
import json, time
from playwright.sync_api import sync_playwright
ROOT=Path(__file__).resolve().parents[1]
HTML=(ROOT/'index.html').read_text()
results=[]; errors=[]
def check(name,fn):
 try:
  result=fn()
  if result is False:raise AssertionError('Check returned False')
  results.append({'name':name,'status':'passed','detail':result})
 except Exception as e:results.append({'name':name,'status':'failed','detail':str(e)[:500]})
with sync_playwright() as p:
 b=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox','--disable-dev-shm-usage'])
 page=b.new_page(viewport={'width':1440,'height':1000})
 page.on('pageerror',lambda e:errors.append(str(e)))
 page.set_content(HTML,wait_until='domcontentloaded');page.wait_for_timeout(450)
 def go(route):
  page.evaluate('(r)=>location.hash=r',route);page.wait_for_timeout(160)
 def no_overflow():return page.evaluate('document.body.scrollWidth<=innerWidth+1')
 check('Home renders all core counts',lambda:page.evaluate('KineticDebug.counts().lessons===61&&KineticDebug.counts().projects===20'))
 page.screenshot(path=str(ROOT/'qa/home-desktop.png'),full_page=True)
 check('Home has no horizontal overflow',no_overflow)
 go('/sandbox/circuit');check('Circuit gives 5.91 mA by default',lambda:'5.91' in page.locator('.sim-metrics').inner_text())
 page.click('[data-lab=switch]');check('Opening the circuit produces zero current',lambda:'0.00' in page.locator('.metric').first.inner_text())
 page.screenshot(path=str(ROOT/'qa/circuit-desktop.png'))
 go('/sandbox/pid');page.click('[data-lab=run]');page.wait_for_timeout(450)
 check('PID simulation advances actual state',lambda:page.evaluate('KineticDebug.lab().motor.t>0.2'))
 page.click('[data-lab=run]');t=page.evaluate('KineticDebug.lab().motor.t');page.wait_for_timeout(80)
 check('Pause freezes simulation time',lambda:abs(page.evaluate('KineticDebug.lab().motor.t')-t)<1e-8)
 page.screenshot(path=str(ROOT/'qa/pid-desktop.png'))
 go('/sandbox/rover');page.click('[data-lab=run]');page.wait_for_timeout(300)
 check('Rover state changes while running',lambda:page.evaluate('KineticDebug.lab().pose.x>0'))
 go('/sandbox/arm');check('Arm reconstructs target',lambda:'Reachable' in page.locator('.sim-metrics').inner_text())
 page.locator('#lab-x').evaluate('(e)=>e.value=0.26');page.locator('#lab-x').dispatch_event('input');page.locator('#lab-y').evaluate('(e)=>e.value=0.26');page.locator('#lab-y').dispatch_event('input')
 check('Arm explicitly reports unreachable target',lambda:'Unreachable' in page.locator('.sim-metrics').inner_text())
 go('/sandbox/path');page.click('[data-lab=block]');check('Blocked path reports no route',lambda:'No path' in page.locator('.sim-metrics').inner_text())
 page.click('[data-lab=clear]');check('Clear grid restores route',lambda:'Found' in page.locator('.sim-metrics').inner_text())
 go('/sandbox/rl');page.click('[data-lab=train]');page.wait_for_function('KineticDebug.lab().learner.episodes===500',timeout=10000)
 check('Q-learning completes 500 real episodes',lambda:page.evaluate('KineticDebug.lab().learner.history.length===500'))
 check('Q-learning evaluation is computed',lambda:page.evaluate('KineticDebug.lab().evaluation.trials===100'))
 go('/learn');check('Curriculum has 12 modules',lambda:page.locator('.module-card').count()==12)
 page.click('[data-action=scope]');check('Eight-semester scope dialog opens',lambda:page.locator('.semester').count()==8);page.click('[data-close]')
 go('/lesson/project-01/check');page.click('[data-answer="1"]');check('Quiz explains correct answer',lambda:'Correct.' in page.locator('.quiz-result').inner_text())
 page.click('[data-answer="0"]');check('Quiz explains incorrect answer',lambda:'Not quite.' in page.locator('.quiz-result').inner_text())
 go('/lesson/circuit-models');check('Plain-language glossary appears',lambda:page.locator('.glossary-term').count()>0)
 page.screenshot(path=str(ROOT/'qa/lesson-desktop.png'))
 go('/project/project-01/2');check('Project wiring stage includes a real connection table',lambda:page.locator('.stage-body table').count()>0 and page.locator('.wiring-stage svg').count()==1)
 page.screenshot(path=str(ROOT/'qa/project-desktop.png'))
 go('/project/project-09/3');page.click('[data-project-code]');page.wait_for_timeout(200)
 check('Native source opens editable without false compilation',lambda:page.locator('#code-lang').input_value()=='native' and len(page.locator('#code-input').input_value())>100)
 go('/code');page.select_option('#code-preset','circuit');page.click('[data-action=run-code]');page.wait_for_timeout(600)
 check('JS worker executes and returns computed values',lambda:'5.91 mA' in page.locator('#code-output').inner_text())
 page.screenshot(path=str(ROOT/'qa/code-desktop.png'))
 page.locator('#code-input').fill("throw new Error('deliberate diagnostic')");page.click('[data-action=run-code]');page.wait_for_timeout(300)
 check('Runtime exception is reported, not swallowed',lambda:'deliberate diagnostic' in page.locator('#code-output').inner_text())
 page.locator('#code-input').fill('while(true){}');page.click('[data-action=run-code]');page.wait_for_timeout(5500)
 check('Infinite computation is terminated by timeout',lambda:'Time limit reached' in page.locator('#code-output').inner_text())
 go('/settings');page.click('[data-theme-choice=ocean]');check('Palette setting updates',lambda:page.evaluate('document.documentElement.dataset.theme==="ocean"'))
 page.select_option('[data-setting=mode]','dark');check('Dark mode updates',lambda:page.evaluate('document.documentElement.dataset.mode==="dark"'))
 page.select_option('[data-setting=motion]','reduced');check('Reduced motion updates',lambda:page.evaluate('document.body.classList.contains("reduce-motion")'))
 page.select_option('[data-setting=mode]','light');page.click('[data-theme-choice=violet]')
 go('/atlas');page.wait_for_timeout(200);check('All real-source assets are represented',lambda:page.locator('.asset-card').count()==51)
 go('/asset/esp');check('Photo failure retains source and explanations',lambda:page.locator('.inspect-panel [data-part]').count()==6 and page.locator('.inspect-text').inner_text()!='')
 page.locator('[data-part="esp:2"]').hover();check('Hover updates the regional explanation',lambda:'USB' in page.locator('.inspect-title').inner_text())
 go('/library');page.click('[data-local-video=pid]');page.wait_for_timeout(350)
 check('Bundled MP4 metadata decodes',lambda:page.evaluate('document.querySelector("video").readyState>=1'))
 check('Bundled clip duration is 8 s',lambda:abs(page.evaluate('document.querySelector("video").duration')-8)<.1)
 page.evaluate('document.querySelector("video").play()');page.wait_for_timeout(300)
 check('Bundled clip playback advances',lambda:page.evaluate('document.querySelector("video").currentTime>0'))
 page.click('[data-close]');go('/home');page.click('[data-action=search]');page.fill('#global-search','Gazebo');check('Global search returns relevant lesson',lambda:'Gazebo' in page.locator('.search-results').inner_text());page.keyboard.press('Escape')
 # Check important views at phone width.
 page.set_viewport_size({'width':390,'height':844})
 for route,name in [('/home','home'),('/sandbox/pid','pid'),('/project/project-01/2','project'),('/code','code'),('/settings','settings'),('/lesson/circuit-models','lesson')]:
  go(route);check('Mobile '+name+' has no horizontal overflow',no_overflow)
  page.screenshot(path=str(ROOT/'qa'/('mobile-'+name+'.png')),full_page=name in ['home','project'])
 check('No uncaught page errors',lambda:len(errors)==0)
 b.close()
report={'environment':'Headless Chromium with set_content; outgoing navigation is administratively disabled. Third-party media/live Python downloads were not validated. Browser persistence across reloads needs a real origin.','passed':sum(t['status']=='passed' for t in results),'failed':sum(t['status']=='failed' for t in results),'uncaught_errors':errors,'tests':results}
(ROOT/'qa/browser-results.json').write_text(json.dumps(report,indent=2))
print(json.dumps(report,indent=2))
