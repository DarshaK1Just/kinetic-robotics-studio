"""Dashboard interactions against real app JavaScript in headless Chromium.
Uses set_content because this environment blocks browser navigation to localhost.
This checks in-page state plus JSON restoration, not origin-based reload persistence.
"""
from pathlib import Path
import json
from playwright.sync_api import sync_playwright
ROOT=Path(__file__).resolve().parents[1]
QA=ROOT/'qa'; QA.mkdir(exist_ok=True)
results=[]; errors=[]

def check(name,fn):
    try:
        v=fn()
        if v is False: raise AssertionError('False result')
        results.append({'name':name,'status':'passed','detail':v})
    except Exception as e:
        results.append({'name':name,'status':'failed','detail':str(e)[:450]})

with sync_playwright() as p:
    browser=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox','--disable-dev-shm-usage'])
    page=browser.new_page(viewport={'width':1440,'height':1024},accept_downloads=True)
    page.set_default_timeout(5000)
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.set_content((ROOT/'index.html').read_text(),wait_until='domcontentloaded')
    page.wait_for_timeout(450)
    def go(path):
        page.evaluate('(r)=>location.hash=r',path);page.wait_for_timeout(150)
    def overflow(): return page.evaluate('document.body.scrollWidth<=innerWidth+1')
    check('Overview routes to a personalized learning dashboard',lambda:'Darshak' in page.locator('h1').inner_text())
    check('Overview preserves all 61 lessons and 20 projects',lambda:page.evaluate('KineticDebug.counts().lessons===61&&KineticDebug.counts().projects===20'))
    check('Overview has six recommended modules',lambda:page.locator('#ks-featured-courses .module-card').count()==6)
    check('New overview navigation is correctly selected',lambda:page.locator('[data-nav=home]').get_attribute('aria-current')=='page')
    page.click('[data-ks=home-filter][data-value=autonomy]')
    check('Autonomy filter shows four advanced modules',lambda:page.locator('#ks-featured-courses .module-card').count()==4)
    page.click('[data-ks=home-filter][data-value=saved]')
    check('Empty saved queue explains how to save a module',lambda:page.locator('.ks-empty').count()==1)
    page.click('[data-ks=home-filter][data-value=foundations]')
    page.click('[data-ks=bookmark][data-id="02"]')
    check('Bookmark button exposes pressed state',lambda:page.locator('[data-ks=bookmark][data-id="02"]').get_attribute('aria-pressed')=='true')
    page.click('[data-ks=home-filter][data-value=saved]')
    check('Saved queue immediately contains the bookmarked module',lambda:page.locator('[data-course="02"]').count()==1)
    check('Bookmark saved in learner state',lambda:page.evaluate('KineticDebug.dashboard().saved.includes("02")'))
    go('/learn')
    check('Catalog includes 12 modules',lambda:page.locator('#ks-catalog .module-card').count()==12)
    page.fill('#ks-module-query','feedback')
    check('Curriculum search filters by subtitle as well as name',lambda:page.locator('#ks-catalog [data-course="06"]').count()==1 and page.locator('#ks-catalog .module-card').count()==1)
    page.fill('#ks-module-query','zzzz-no-module')
    check('No-result search provides an explicit empty state',lambda:'Nothing here' in page.locator('#ks-catalog').inner_text())
    page.fill('#ks-module-query','')
    page.click('[data-ks=filter][data-value=saved]')
    check('Catalog saved filter retains prior bookmarks',lambda:page.locator('#ks-catalog .module-card').count()==1)
    page.click('[data-ks=filter][data-value=all]')
    page.click('[data-ks=layout][data-value=list]')
    check('List view is functional rather than decorative',lambda:page.locator('#ks-catalog.ks-list-view').count()==1)
    page.click('[data-ks=layout][data-value=grid]')
    go('/module/02')
    check('Expanded module has five existing lesson routes',lambda:page.locator('.ks-path-lesson').count()==5)
    check('Module save control reflects bookmark state',lambda:page.locator('.ks-save-module').get_attribute('aria-pressed')=='true')
    page.focus('#ks-tab-lessons');page.keyboard.press('ArrowRight')
    check('Arrow key moves focus without unexpected tab activation',lambda:page.evaluate('document.activeElement.id==="ks-tab-practice"') and page.locator('#ks-tab-lessons').get_attribute('aria-selected')=='true')
    page.keyboard.press('Enter');page.wait_for_timeout(250)
    check('Enter activates module practice tab and renders lab link',lambda:page.locator('#ks-tab-practice').get_attribute('aria-selected')=='true' and page.locator('.ks-practice-art a[href="#/sandbox/circuit"]').count()==1)
    page.click('#ks-tab-evidence');page.wait_for_timeout(250)
    page.fill('#ks-evidence-note','Prediction: 5.91 mA at 220 ohms. Compare against a real measurement.')
    page.check('[data-ks-evidence="02"][data-index="0"]')
    check('Evidence note is retained in learner state',lambda:page.evaluate('KineticDebug.dashboard().evidence["02"].note.includes("5.91")'))
    check('Evidence rubric saves independently of lesson completion',lambda:page.evaluate('KineticDebug.dashboard().evidence["02"].checks[0]&&!KineticDebug.state().complete["circuit-models"]'))
    with page.expect_download() as dl: page.click('[data-ks=export-evidence]')
    dl.value.save_as(str(QA/'evidence-fixture.md'))
    check('Evidence downloads as readable Markdown',lambda:'5.91 mA' in (QA/'evidence-fixture.md').read_text())
    go('/module/03');go('/module/02/evidence')
    check('Evidence survives route changes',lambda:'5.91' in page.locator('#ks-evidence-note').input_value())
    go('/home')
    check('LED challenge shows an actual computed default current',lambda:'5.91' in page.locator('#ks-current').inner_text())
    page.click('[data-ks=check-challenge]')
    check('Challenge requests a prediction before giving a pass',lambda:'prediction first' in page.locator('#ks-challenge-feedback').inner_text())
    page.check('input[name=ks-predict][value=less]')
    page.locator('#ks-resistance').fill('100')
    check('Changing resistance immediately updates model output',lambda:'13.00' in page.locator('#ks-current').inner_text())
    page.click('[data-ks=check-challenge]')
    check('Unsafe target current is not marked as passing',lambda:page.locator('#ks-challenge-feedback.is-retry').count()==1)
    page.locator('#ks-resistance').fill('220');page.click('[data-ks=check-challenge]')
    check('Correct prediction and resistance pass with numerical reasoning',lambda:page.locator('#ks-challenge-feedback.is-correct').count()==1 and '5.91' in page.locator('#ks-challenge-feedback').inner_text())
    check('Challenge stores its inputs and outcome',lambda:page.evaluate('KineticDebug.dashboard().challenge.passed&&KineticDebug.dashboard().challenge.resistance===220'))
    page.check('input[name=ks-predict][value=more]');page.click('[data-ks=check-challenge]')
    check('Wrong conceptual prediction does not pass despite current below limit',lambda:page.locator('#ks-challenge-feedback.is-retry').count()==1)
    page.click('[data-ks=timer-duration][data-value="25"]')
    check('Focus duration changes to 25 minutes',lambda:page.locator('#ks-timer-display').inner_text()=='25:00')
    page.click('[data-ks=timer-toggle]');page.wait_for_timeout(1200)
    check('Focus timer advances based on its deadline',lambda:page.locator('#ks-timer-display').inner_text()!='25:00')
    page.click('[data-ks=timer-toggle]');before=page.locator('#ks-timer-display').inner_text();page.wait_for_timeout(1100)
    check('Pausing the focus timer freezes remaining time',lambda:page.locator('#ks-timer-display').inner_text()==before)
    page.click('[data-ks=timer-reset]')
    check('Reset clears the deadline without inventing a completed session',lambda:page.evaluate('KineticDebug.dashboard().timer.deadline===0&&KineticDebug.dashboard().sessions.length===0'))
    page.evaluate('KineticDebug.dashboard().timer.deadline=Date.now()-1')
    page.wait_for_timeout(650)
    check('One elapsed timer records exactly one completed session',lambda:page.evaluate('KineticDebug.dashboard().sessions.length===1'))
    check('Completed focus minutes update the overview immediately',lambda:'25' in page.locator('.ks-stat').nth(3).inner_text())
    page.wait_for_timeout(650)
    check('Timer completion is not duplicated on subsequent ticks',lambda:page.evaluate('KineticDebug.dashboard().sessions.length===1'))
    go('/lesson/engineering-method');page.click('[data-action=complete]');go('/home')
    check('Overview displays actual reviewed lesson count',lambda:'1' in page.locator('.ks-stat').first.inner_text())
    check('Next lesson advances beyond a completed lesson',lambda:page.locator('.ks-next-card a').get_attribute('href')!='#/lesson/engineering-method')
    go('/settings')
    with page.expect_download() as export:page.click('[data-action=export-progress]')
    export.value.save_as(str(QA/'dashboard-progress-fixture.json'))
    fixture=json.loads((QA/'dashboard-progress-fixture.json').read_text())
    check('Progress export includes bookmarks and new evidence',lambda:fixture['dashboard']['saved']==['02'] and '5.91' in fixture['dashboard']['evidence']['02']['note'])
    fixture['dashboard']['saved']=['04'];fixture['dashboard']['evidence']['02']['note']='Restored evidence.'
    with page.expect_file_chooser() as chooser:page.click('[data-action=import-progress]')
    chooser.value.set_files({'name':'progress.json','mimeType':'application/json','buffer':json.dumps(fixture).encode()})
    page.wait_for_timeout(250)
    check('Progress import restores new dashboard fields',lambda:page.evaluate('KineticDebug.dashboard().saved[0]==="04"&&KineticDebug.dashboard().evidence["02"].note==="Restored evidence."'))
    page.select_option('[data-setting=motion]','reduced');go('/home')
    check('Reduced motion stops decorative floating animation',lambda:page.locator('.ks-float-tag').evaluate('(el)=>getComputedStyle(el).animationName')=='none')
    # Test preference modes and viewport geometry, not external media availability.
    go('/settings');page.select_option('[data-setting=mode]','dark');go('/home')
    page.wait_for_timeout(300);page.screenshot(path=str(QA/'redesign-dark.png'))
    check('Dark palette is applied to the new dashboard',lambda:page.evaluate('document.documentElement.dataset.mode==="dark"'))
    go('/settings');page.select_option('[data-setting=mode]','light');page.select_option('[data-setting=scale]','1.2');go('/learn')
    check('Comfort text setting does not create desktop overflow',overflow)
    go('/settings');page.select_option('[data-setting=scale]','1')
    for width in [390,768,1440,1920]:
        page.set_viewport_size({'width':width,'height':1000 if width>640 else 844})
        for route in ['/home','/learn','/module/02','/module/02/practice','/module/02/evidence','/sandbox/pid','/code']:
            go(route)
            check(f'No horizontal overflow: {width}px {route}',overflow)
    # Capture final application, not a visual mockup.
    page.set_viewport_size({'width':1440,'height':1024})
    page.evaluate('KineticDebug.state().complete={};KineticDebug.state().quizzes={};KineticDebug.state().name="Darshak";KineticDebug.state().dashboard=KineticDashboard.sanitize({});')
    go('/learn');page.click('[data-ks=filter][data-value=all]');page.click('[data-ks=layout][data-value=grid]')
    page.wait_for_timeout(300);page.screenshot(path=str(QA/'redesign-curriculum.png'),full_page=True)
    go('/home');page.click('[data-ks=home-filter][data-value=all]');page.wait_for_timeout(300)
    page.screenshot(path=str(QA/'redesign-dashboard.png'))
    page.screenshot(path=str(QA/'redesign-dashboard-full.png'),full_page=True)
    go('/module/02');page.wait_for_timeout(300);page.screenshot(path=str(QA/'redesign-module.png'),full_page=True)
    go('/module/02/evidence');page.wait_for_timeout(300);page.screenshot(path=str(QA/'redesign-evidence.png'))
    page.set_viewport_size({'width':390,'height':844});go('/home');page.wait_for_timeout(300);page.screenshot(path=str(QA/'redesign-mobile.png'))
    check('No uncaught JavaScript error in dashboard interaction suite',lambda:not errors)
    browser.close()
report={'environment':'Headless Chromium set_content fixture; external navigation blocked. In-page state and JSON export/import tested. Origin-backed reload persistence and remote media not verified.', 'passed':sum(r['status']=='passed' for r in results),'failed':sum(r['status']=='failed' for r in results),'uncaught_errors':errors,'tests':results}
(QA/'dashboard-browser-results.json').write_text(json.dumps(report,indent=2))
print(json.dumps(report,indent=2))
if report['failed']:raise SystemExit(1)
